// Builds the optional AI add-on: autofill-smart.js (put it next to autofill.html).
// Contains transformers.js, the ONNX runtime and a small multilingual sentence model
// (paraphrase-multilingual-MiniLM-L12-v2, int8), all gzipped + base64 so it loads from file://.
// Model files are expected in smart/download (see README).
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const p = (x) => new URL(x, import.meta.url);
const pack = (path) => gzipSync(readFileSync(p(path)), { level: 9 }).toString('base64');
const data = {
  transformers: pack('./node_modules/@huggingface/transformers/dist/transformers.min.js'),
  ortMjs: pack('./node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.asyncify.mjs'),
  ortWasm: pack('./node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.asyncify.wasm'),
  files: {},
};
for (const f of ['config.json', 'tokenizer.json', 'tokenizer_config.json', 'special_tokens_map.json', 'onnx/model_quantized.onnx']) {
  data.files[f] = pack('./smart/download/' + f);
}
const js = '// AutoFill smart matching add-on (generated by build-smart.mjs)\nwindow.AF_SMART = ' + JSON.stringify(data) + ';\n';
writeFileSync(p('./autofill-smart.js'), js);
console.log(`autofill-smart.js: ${(js.length / 1024 / 1024).toFixed(1)} MB`);
